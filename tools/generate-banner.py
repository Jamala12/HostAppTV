#!/usr/bin/env python3
"""Generate the TV launcher VectorDrawable from the bundled OFL Gelasio font.

Run with Python 3 and fontTools installed. No raster tooling or runtime font is needed.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[1]
font = TTFont(ROOT / 'app/src/main/res/font/gelasio.ttf')
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
label = 'HostAppTV'
scale = 30 / font['head'].unitsPerEm
advances = [font['hmtx'][cmap[ord(c)]][0] * scale for c in label]
width = sum(advances)
# Match the existing asymmetric emblem; center the complete lockup in a 16:9 canvas.
emblem_size, gap = 48, 18
left = (320 - emblem_size - gap - width) / 2
x = left + emblem_size + gap
paths = []
for character, advance in zip(label, advances):
    pen = SVGPathPen(glyphs)
    glyphs[cmap[ord(character)]].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 100)))
    paths.append(pen.getCommands())
    x += advance
emblem_scale = emblem_size / 44
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate-banner.py. Wordmark outlines: bundled Gelasio (SIL OFL 1.1). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="320dp" android:height="180dp"
    android:viewportWidth="320" android:viewportHeight="180">
    <path android:fillColor="#0B1013" android:pathData="M0,0H320V180H0Z" />
    <group android:translateX="{left:.3f}" android:translateY="64" android:scaleX="{emblem_scale:.6f}" android:scaleY="{emblem_scale:.6f}">
        <path android:pathData="M16,0 H34 A10,10 0 0 1 44,10 V42 A3,3 0 0 1 41,45 H10 A10,10 0 0 1 0,35 V16 A16,16 0 0 1 16,0 Z"
            android:fillColor="#00000000" android:strokeColor="#79936D" android:strokeWidth="1.6" />
        <path android:pathData="M15,13 L33,23 L15,33 Z" android:fillColor="#CBDCAC" />
    </group>
    <path android:fillColor="#EEF1ED" android:pathData="{''.join(paths)}" />
</vector>
'''
(ROOT / 'app/src/main/res/drawable/banner.xml').write_text(xml)
print('Generated HostAppTV launcher banner (320 × 180 vector).')
